// Validation Check
const seenBarcodes = new Set();
const seenIds = new Set();
let errorCount = 0;

for (const item of fullCatalog) {
  if (!item.barcode || seenBarcodes.has(item.barcode)) {
    console.error(`Duplicate or missing barcode: ${item.barcode} (${item.name})`);
    errorCount++;
  }
  seenBarcodes.add(item.barcode);

  if (!item.id || seenIds.has(item.id)) {
    console.error(`Duplicate or missing ID: ${item.id}`);
    errorCount++;
  }
  seenIds.add(item.id);

  if (!item.name || !item.manufacturer || !item.category || !item.unit) {
    console.error(`Missing metadata fields in item: ${item.id}`);
    errorCount++;
  }

  // Check 7 chains prices
  const chains = ['rami_levy', 'osher_ad', 'yochananof', 'shufersal_deal', 'carrefour', 'victory', 'hazi_hinam'];
  for (const ch of chains) {
    const p = item.prices[ch];
    if (typeof p !== 'number' || isNaN(p) || p <= 0) {
      console.error(`Invalid price for chain ${ch} in item ${item.id}: ${p}`);
      errorCount++;
    }
  }
}

if (errorCount > 0) {
  console.error(`❌ Validation failed with ${errorCount} errors!`);
  process.exit(1);
}

